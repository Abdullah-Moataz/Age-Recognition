import streamlit as st
import numpy as np
from PIL import Image
from tensorflow.keras.models import load_model

st.set_page_config(
    page_title="Age Prediction",
    page_icon="🎂",
    layout="centered"
)

@st.cache_resource
def load_age_model():
    return load_model("age_model.keras")

model = load_age_model()

st.title("🎂 Age Prediction Using CNN")
st.write("Upload a face image and let the CNN predict the person's age!")

option = st.radio(
    "Choose input method:",
    ["Upload Image", "Take Photo"]
)

if option == "Upload Image":
    uploaded_file = st.file_uploader(
        "Choose an image",
        type=["jpg", "jpeg", "png"]
    )
else:
    uploaded_file = st.camera_input("Take a photo")

if uploaded_file is not None:
    image = Image.open(uploaded_file).convert("RGB")

    st.image(image, caption="Uploaded Image", use_container_width=True)

    # Preprocess image
    img = image.resize((48, 48))
    img_array = np.array(img, dtype=np.float32) / 255.0
    img_array = np.expand_dims(img_array, axis=0)

    if st.button("Predict Age"):
        with st.spinner("Predicting age..."):
            prediction = model.predict(img_array, verbose=0)
            predicted_age = float(prediction[0][0])

            predicted_age = max(0, round(predicted_age))

        st.success("Prediction Complete!")
        st.metric("Predicted Age", f"{predicted_age} years")

        st.info(
            "Note: This is an estimated age generated by a CNN model. "
            "The prediction may differ from the person's actual age."
        )